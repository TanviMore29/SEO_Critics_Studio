"""
reports/excel_report_generator.py

Generates a formatted Excel (.xlsx) SEO report with a summary sheet
and a page-level details sheet, using openpyxl.
"""

import os
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment

OUTPUT_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "reports_output", "excel")
os.makedirs(OUTPUT_DIR, exist_ok=True)

HEADER_FILL = PatternFill(start_color="14213D", end_color="14213D", fill_type="solid")
HEADER_FONT = Font(color="FFFFFF", bold=True)


def _style_header(ws, row=1):
    for cell in ws[row]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center")


def generate_excel_report(website: dict, scores: dict, pages: list, sitemap_data: dict, robots_data: dict,
                           recommendations: list = None, site_keywords: list = None,
                           advanced_checks: dict = None) -> str:
    recommendations = recommendations or []
    site_keywords = site_keywords or []
    advanced_checks = advanced_checks or {}
    total_pages = advanced_checks.get("total_pages", len(pages)) or 1

    wb = Workbook()

    # --- Summary Sheet ---
    summary = wb.active
    summary.title = "Summary"
    summary.append(["SEO Critics Studio - Analysis Summary"])
    summary["A1"].font = Font(bold=True, size=14)
    summary.append([])
    summary.append(["Website", website["root_url"]])
    summary.append(["Domain", website["domain_name"]])
    summary.append(["Pages Scanned", len(pages)])
    summary.append(["Overall Score", f"{scores['overall_score']} / 100"])
    summary.append(["Health Level", scores["health_level"]])
    summary.append([])
    summary.append(["Category", "Score", "Max"])
    _style_header(summary, row=9)
    max_scores = scores["max_scores"]
    for label, key, maxkey in [
        ("Metadata", "metadata_score", "metadata"),
        ("Technical SEO", "technical_score", "technical"),
        ("Images", "images_score", "images"),
        ("Links", "links_score", "links"),
        ("Sitemap", "sitemap_score", "sitemap"),
        ("robots.txt", "robots_score", "robots"),
        ("Performance", "performance_score", "performance"),
    ]:
        summary.append([label, scores[key], max_scores[maxkey]])

    summary.append([])
    summary.append(["sitemap.xml exists", "Yes" if sitemap_data.get("exists") else "No"])
    summary.append(["sitemap.xml URL count", sitemap_data.get("url_count", 0)])
    summary.append(["robots.txt exists", "Yes" if robots_data.get("exists") else "No"])

    summary.append([])
    summary.append(["Additional Technical Signals", "Coverage"])
    _style_header(summary, row=summary.max_row)
    summary.append(["Pages with mobile viewport tag", f"{advanced_checks.get('pages_with_viewport', 0)} / {total_pages}"])
    summary.append(["Pages with structured data", f"{advanced_checks.get('pages_with_structured_data', 0)} / {total_pages}"])
    summary.append(["Pages with Open Graph tags", f"{advanced_checks.get('pages_with_open_graph', 0)} / {total_pages}"])
    summary.append(["Pages with Twitter Card tags", f"{advanced_checks.get('pages_with_twitter_card', 0)} / {total_pages}"])
    summary.append(["Pages with declared language", f"{advanced_checks.get('pages_with_lang', 0)} / {total_pages}"])

    for col, width in zip("ABC", [30, 40, 12]):
        summary.column_dimensions[col].width = width

    # --- Recommendations Sheet ---
    rec_sheet = wb.create_sheet("Recommendations")
    rec_sheet.append(["Priority", "Recommendation", "Details", "Affected Pages"])
    _style_header(rec_sheet, row=1)
    for r in recommendations:
        rec_sheet.append([r["priority"].upper(), r["title"], r["description"], r.get("affected_pages") or ""])
    if not recommendations:
        rec_sheet.append(["-", "No issues detected", "Great work — no rule-based recommendations triggered.", ""])
    rec_sheet.append([])
    rec_sheet.append(["Note: recommendations are generated by fixed rule-based checks against the scan results, not an AI model."])
    for col, width in zip("ABCD", [12, 34, 70, 16]):
        rec_sheet.column_dimensions[col].width = width

    # --- Keywords Sheet ---
    kw_sheet = wb.create_sheet("Top Keywords")
    kw_sheet.append(["Keyword", "Occurrences", "Site-wide Density (%)"])
    _style_header(kw_sheet, row=1)
    for kw in site_keywords:
        kw_sheet.append([kw["keyword"], kw["count"], kw["density"]])
    for col, width in zip("ABC", [26, 16, 20]):
        kw_sheet.column_dimensions[col].width = width

    # --- Page Details Sheet ---
    details = wb.create_sheet("Page Details")
    headers = [
        "Page URL", "Status Code", "Title", "Meta Description", "Canonical URL",
        "H1 Count", "H2 Count", "Word Count", "Internal Links", "External Links",
        "Broken Links", "Image Count", "Images Missing ALT", "HTTPS",
        "Page Size (KB)", "Response Time (ms)", "Has Viewport", "Has Structured Data",
        "Has Open Graph", "Has Twitter Card", "HTML Lang",
    ]
    details.append(headers)
    _style_header(details, row=1)

    for p in pages:
        details.append([
            p.get("page_url"), p.get("status_code"), p.get("title"),
            p.get("meta_description"), p.get("canonical_url"),
            p.get("h1_count"), p.get("h2_count"), p.get("word_count"),
            p.get("internal_links"), p.get("external_links"), p.get("broken_links"),
            p.get("image_count"), p.get("images_missing_alt"),
            "Yes" if p.get("is_https") else "No",
            p.get("page_size_kb"), p.get("response_time_ms"),
            "Yes" if p.get("has_viewport") else "No",
            "Yes" if p.get("has_structured_data") else "No",
            "Yes" if p.get("has_open_graph") else "No",
            "Yes" if p.get("has_twitter_card") else "No",
            p.get("html_lang") or "",
        ])

    widths = [40, 12, 30, 30, 30, 10, 10, 12, 12, 12, 12, 12, 16, 8, 14, 16, 12, 16, 14, 14, 10]
    for i, width in enumerate(widths):
        col_letter = details.cell(row=1, column=i + 1).column_letter
        details.column_dimensions[col_letter].width = width

    file_path = os.path.join(OUTPUT_DIR, f"{website['domain_name']}_seo_report.xlsx")
    wb.save(file_path)
    return file_path
